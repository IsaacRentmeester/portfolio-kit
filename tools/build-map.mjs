// Builds content/map-base.js: simplified state/province outlines + Great Lakes for the story map.
// Source: Natural Earth 1:50m (public domain). Run once when the map area changes:
//   node tools/build-map.mjs <ne_50m_admin_1_states_provinces.geojson> <ne_50m_lakes.geojson>
import { readFileSync, writeFileSync } from "node:fs";

const [adminPath, lakesPath] = process.argv.slice(2);
if (!adminPath || !lakesPath) { console.error("[build-map] usage: node tools/build-map.mjs <admin1.geojson> <lakes.geojson>"); process.exit(1); }

const BOX = { w: -101, e: -66, s: 38, n: 52 };   // area around all map stops (a bit past the visible map)
const TOL = 0.12;                                  // degrees; drop points closer than this
const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const inBox = ([x0, y0, x1, y1]) => x1 >= BOX.w && x0 <= BOX.e && y1 >= BOX.s && y0 <= BOX.n;
const bboxOf = (rings) => {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const r of rings) for (const [x, y] of r) { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); }
  return [x0, y0, x1, y1];
};
const polys = (g) => (g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : []);

// Keep only the outer ring of each polygon, thinned, rounded to 2 decimals.
function simplify(ring) {
  const out = [];
  for (const [rx, ry] of ring) {
    // Clamp to the box: parts outside it collapse onto the edge, which is off-screen anyway.
    const x = Math.min(Math.max(rx, BOX.w), BOX.e), y = Math.min(Math.max(ry, BOX.s), BOX.n);
    const p = [Math.round(x * 100) / 100, Math.round(y * 100) / 100];
    const last = out[out.length - 1];
    if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) >= TOL) out.push(p);
  }
  return out.length > 3 ? out : null;
}

const regions = [];
for (const f of read(adminPath).features) {
  const { admin, postal, name } = f.properties;
  if (admin !== "United States of America" && admin !== "Canada") continue;
  const rings = polys(f.geometry).map((p) => p[0]);
  const bb = bboxOf(rings);
  if (!inBox(bb)) continue;
  const area = (r) => { const [a, b, c, d] = bboxOf([r]); return (c - a) * (d - b); };
  const kept = rings.filter((r) => inBox(bboxOf([r])) && area(r) > 0.15).map(simplify).filter(Boolean);  // skip tiny islands
  if (!kept.length) continue;
  // Label at the centre of the largest ring's bbox, nudged into the visible box.
  const big = kept.reduce((a, r) => { const b = bboxOf([r]); return (b[2] - b[0]) * (b[3] - b[1]) > a.s ? { r, s: (b[2] - b[0]) * (b[3] - b[1]) } : a; }, { r: kept[0], s: 0 }).r;
  const [x0, y0, x1, y1] = bboxOf([big]);
  const lon = Math.min(Math.max((x0 + x1) / 2, BOX.w + 2), BOX.e - 2), lat = Math.min(Math.max((y0 + y1) / 2, BOX.s + 1), BOX.n - 1);
  regions.push({ code: postal || name.slice(0, 2).toUpperCase(), name, label: [Math.round(lon * 10) / 10, Math.round(lat * 10) / 10], rings: kept });
}

const LAKES = /^Lake (Superior|Michigan|Huron|Erie|Ontario|Winnipeg)$/;
const lakes = [];
for (const f of read(lakesPath).features) {
  if (!LAKES.test(f.properties.name || "")) continue;
  for (const p of polys(f.geometry)) { const r = simplify(p[0]); if (r) lakes.push(r); }
}

const out = `// Generated by tools/build-map.mjs from Natural Earth (public domain). Do not edit by hand.
// rings: [[lon, lat], ...]; label: [lon, lat] where the state/province code sits.
export const mapBase = ${JSON.stringify({ regions, lakes })};
`;
writeFileSync(new URL("../content/map-base.js", import.meta.url), out);
console.log(`[build-map] ${regions.length} regions, ${lakes.length} lake shapes, ${(out.length / 1024).toFixed(1)} KB`);
